'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { scryptSync, randomBytes, timingSafeEqual } = require('node:crypto');
const base=path.resolve(__dirname,'..');
const read=(p)=>fs.readFileSync(path.join(base,p),'utf8');
const sql=read('sql/03_Thiet_Lap_Dang_Nhap.sql');
const svc=read('src/auth/auth.service.ts');
const ctrl=read('src/auth/auth.controller.ts');
const ui=read('public/js/gds-auth.js');
assert.match(sql,/USE \[GocDanSinh\]/);
assert.match(sql,/CREATE TABLE dbo\.auth_credential/);
assert.match(sql,/CREATE TABLE dbo\.auth_session/);
assert.doesNotMatch(sql,/DROP TABLE|DELETE FROM dbo\.app_user|UPDATE dbo\.knowledge_version|published_at\s*=/i);
assert.match(svc,/scrypt/);
assert.match(svc,/timingSafeEqual/);
assert.match(svc,/BEGIN TRAN/);
assert.match(svc,/ROLLBACK TRAN/);
assert.match(ctrl,/httpOnly:true/);
assert.match(ctrl,/sameSite:'strict'/);
assert.match(ui,/api\/auth\//);
assert.doesNotMatch(ui,/localStorage|sessionStorage/);
assert.match(read('src/app.module.ts'),/AuthModule/);
for(const file of ['public/index.html','public/login.html','public/register.html'])
  assert.match(read(file),/src=\"\/js\/gds-auth\.js\"/);
const salt=randomBytes(32), passwd='MyTempStrongPass123!';
const hashed=scryptSync(passwd,salt,64,{N:16384,r:8,p:1,maxmem:64*1024*1024});
assert.equal(timingSafeEqual(hashed,scryptSync(passwd,salt,64,{N:16384,r:8,p:1,maxmem:64*1024*1024})),true);
assert.equal(timingSafeEqual(hashed,scryptSync('not-the-same-password',salt,64,{N:16384,r:8,p:1,maxmem:64*1024*1024})),false);
console.log('PASS: auth SQL migration isolated, registration transaction, hashed passwords, HttpOnly session, auth pages wired');
